#!/usr/bin/env python3
"""Extract ASCII pixel glyphs used by the Tufty MicroPython disk screen."""
import argparse
import hashlib
from pathlib import Path
import struct


def extract(path):
    data=path.read_bytes()
    if len(data)<46 or data[:8]!=b'ppf!\0\0\0\0':
        raise ValueError(f'{path}: unsupported PPF header')
    count,width,height=struct.unpack_from('>HHH',data,8)
    stride=(width+7)//8
    if not 0<width<=16 or not 0<height<=32 or len(data)!=46+count*(6+stride*height):
        raise ValueError(f'{path}: invalid PPF dimensions or length')
    start=46+count*6
    glyphs={}
    for i in range(count):
        code,ink=struct.unpack_from('>IH',data,46+i*6)
        if ink>width or code in glyphs:
            raise ValueError(f'{path}: invalid glyph table')
        offset=start+i*stride*height
        rows=[int.from_bytes(data[offset+y*stride:offset+(y+1)*stride],'big')<<(16-stride*8)
              for y in range(height)]
        glyphs[code]=(ink,rows)
    widths=[]; rows=[]
    for code in range(32,127):
        ink,bits=glyphs[code]
        widths.append(width//3 if code==32 else ink+1)
        rows.extend(bits)
    return width,height,widths,rows,hashlib.sha256(data).hexdigest()


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--reference',type=Path,required=True,help='Pimoroni tufty2350 source checkout')
    parser.add_argument('--output',type=Path,default=Path(__file__).resolve().parents[1]/'src/disk_fonts.hpp')
    args=parser.parse_args()
    lines=['// Generated by tools/generate_disk_fonts.py from Pimoroni Tufty ROM fonts.',
           '// See THIRD_PARTY.md for source attribution.', '#pragma once', '#include <cstdint>',
           'namespace disk_art {',
           'struct Font { uint8_t width,height; const uint8_t *advance; const uint16_t *rows; };']
    for name in ('ark','absolute'):
        width,height,advance,rows,digest=extract(args.reference/'romfs/fonts'/f'{name}.ppf')
        lines.append(f'// {name}.ppf SHA256: {digest}')
        lines.append(f'inline constexpr uint8_t {name}_advance[]={{'+','.join(map(str,advance))+'};')
        lines.append(f'inline constexpr uint16_t {name}_rows[]={{')
        for i in range(0,len(rows),height):
            lines.append(','.join(f'0x{x:04x}' for x in rows[i:i+height])+',')
        lines.extend(['};',f'inline constexpr Font {name}{{{width},{height},{name}_advance,{name}_rows}};'])
    lines.append('}')
    args.output.write_text('\n'.join(lines)+'\n')


if __name__=='__main__':
    main()
