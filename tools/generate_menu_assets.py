#!/usr/bin/env python3
"""Generate checked-in native menu assets from office artwork and OFL Lato fonts."""
import argparse
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--reference',type=Path,required=True)
    p.add_argument('--fonts',type=Path,default=Path('/usr/share/fonts/truetype/lato'))
    a=p.parse_args()
    output=Path(__file__).resolve().parents[1]/'src/menu_assets.hpp'
    with output.open('w') as f:
        f.write('// Generated by tools/generate_menu_assets.py. Lato: SIL OFL 1.1.\n#pragma once\n#include <cstdint>\nnamespace art {\n')
        bg=Image.open(a.reference/'office/assets/background.png').convert('RGB').resize((320,200))
        values=[((r>>3)<<11)|((g>>2)<<5)|(b>>3) for r,g,b in bg.getdata()]
        f.write('inline const uint16_t background[64000]={\n')
        for i in range(0,len(values),24): f.write(','.join(str(x) for x in values[i:i+24])+',\n')
        f.write('};\nstruct Glyph { uint16_t offset; uint8_t width, height, advance; };\n')
        for name,size,weight in [('body',14,'Regular'),('title',25,'Heavy'),('header',18,'Bold')]:
            font=ImageFont.truetype(str(a.fonts/f'Lato-{weight}.ttf'),size)
            pixels=[]; glyphs=[]
            for code in range(32,127):
                c=chr(code); width=max(1,int(font.getlength(c)+1)); height=size+5
                im=Image.new('L',(width,height)); ImageDraw.Draw(im).text((0,0),c,font=font,fill=255)
                glyphs.append((len(pixels),width,height,int(font.getlength(c)+0.5)))
                pixels.extend(im.getdata())
            f.write(f'inline const uint8_t {name}_pixels[]={{\n')
            for i in range(0,len(pixels),40): f.write(','.join(str(x) for x in pixels[i:i+40])+',\n')
            f.write('};\n')
            f.write(f'inline const Glyph {name}_glyphs[95]={{\n')
            f.write(',\n'.join('{%d,%d,%d,%d}'%g for g in glyphs)+'\n};\n')
        f.write('}\n')

if __name__=='__main__': main()
